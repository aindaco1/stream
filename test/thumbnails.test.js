import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import sharp from 'sharp';
import { openSetupStore } from '../src/setup-store.js';
import { createThumbnails, thumbnailScope } from '../src/thumbnails.js';
import { centerFrame } from '../src/thumbnail-frame.js';
import { thumbnailGrant } from '../public/thumbnail-grant.js';
import { thumbnailBucket, testWriterId, testWriterSecret } from './fixtures/thumbnail-r2.js';

test('private R2 artwork can be uploaded, reframed, replaced and deleted with a film-specific grant', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'stream-posters-'));
  const store = openSetupStore(directory);
  t.after(async () => { store.close(); await rm(directory, { recursive: true, force: true }); });
  const owner = 'Ada', id = 'f-' + randomUUID();
  const bucket = { accountId: 'a'.repeat(32), bucket: 'screening-room', jurisdiction: 'eu' };
  store.signIn(store.invite(owner));
  store.saveBucket(owner, { ...bucket, accessKeyId: 'reader', secretAccessKey: 'read-secret' });
  store.saveFilm(owner, bucket, { id, objectKey: 'original.mp4' });
  const film = () => store.film(owner, id);
  const { objects, fetcher } = thumbnailBucket();
  const thumbnails = createThumbnails(store, fetcher);
  const scoped = (record, secret = testWriterSecret) => {
    const scope = thumbnailScope(record);
    return thumbnailGrant({ ...scope, account: scope.accountId }, testWriterId, secret);
  };
  const { jwt } = await scoped(film());
  const blue = await sharp({ create: { width: 180, height: 160, channels: 3, background: '#246acf' } }).png().toBuffer();
  const change = (params = {}) => thumbnails.change(owner, film(), { jwt, version: film().thumbnail || '', frame: centerFrame, ...params });
  await assert.rejects(change({ input: Buffer.from('not an image') }), { status: 422 });
  await assert.rejects(change({ input: blue, jwt: (await scoped({ ...film(), id: 'f-' + randomUUID() })).jwt }), { status: 403 });
  await assert.rejects(change({ input: blue, jwt: (await scoped(film(), '9'.repeat(64))).jwt }), { status: 403 });
  assert.equal(objects.size, 0);
  assert.ok(!film().thumbnail);
  const first = await change({ input: blue });
  assert.equal(objects.size, 1);
  assert.equal(first, film().thumbnail);
  const original = (await thumbnails.read(owner, film())).data;
  const initial = await sharp(await thumbnails.poster(owner, film())).metadata();
  assert.equal(initial.width, 180);
  assert.equal(initial.height, 101);
  const frame = { x: 50, y: 90, zoom: 200 };
  await change({ frame });
  assert.deepEqual((await thumbnails.read(owner, film())).data, original);
  assert.equal((await sharp(await thumbnails.poster(owner, film())).metadata()).width, 90);
  await assert.rejects(change({ version: first, remove: true }), { status: 409 });
  const lock = store.beginThumbnailEdit(owner, id);
  await assert.rejects(change({ remove: true }), { status: 409 });
  store.finishThumbnailEdit(owner, id, lock);
  await change({ input: await sharp(blue).grayscale().webp().toBuffer() });
  assert.notDeepEqual((await thumbnails.read(owner, film())).data, original);
  assert.equal(objects.size, 1);
  await change({ remove: true });
  assert.equal(objects.size, 0);
  assert.equal(await thumbnails.poster(owner, film()), undefined);
  assert.equal(await thumbnails.read(owner, film()), null);
  assert.equal(film().objectKey, 'original.mp4');
});
